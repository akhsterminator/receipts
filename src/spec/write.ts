import { asOf, type ReceiptsConfig } from "../config.js";
import type { Store } from "../store.js";
import type { Opportunity, Quote } from "../types.js";
import { humanAge, plural } from "../util.js";
import { VERSION } from "../version.js";

export interface WriteSpecOptions {
  /** Maximum number of requirements (highest score first). */
  top?: number;
  /** Inline quotes shown under each requirement. */
  quotesPerRequirement?: number;
  /** Relative path from the spec to the store, shown in the header. */
  storePath?: string;
  /** Maximum quote IDs in a `because:` line. */
  maxCitations?: number;
}

/**
 * Which quotes to cite: the strongest quote from each customer (so the count
 * of citations is a count of voices, not of repetitions), strongest first.
 */
export function citations(store: Store, o: Opportunity, max: number): string[] {
  const rank = (x: Quote) => {
    const src = store.source(x.sourceId);
    return (
      x.intensity +
      (x.kind === "pain" || x.kind === "request" ? 0.2 : 0) +
      (x.text.length > 30 ? 0.1 : 0) +
      (x.id === o.representativeQuoteId ? 1 : 0) +
      // A customer's own title for an issue or ticket is their clearest statement of the need.
      (src && x.start === 0 && x.text === src.title ? 0.4 : 0)
    );
  };
  const best = new Map<string, Quote>();
  for (const id of o.quoteIds) {
    const q = store.quote(id);
    if (!q) continue;
    const cur = best.get(q.customer);
    if (!cur || rank(q) > rank(cur)) best.set(q.customer, q);
  }
  const order = new Map(o.quoteIds.map((id, i) => [id, i]));
  return [...best.values()]
    .sort((a, b) => (order.get(a.id)! - order.get(b.id)!))
    .slice(0, max)
    .map((q) => q.id);
}

export function evidenceComment(o: Opportunity, now: Date): string {
  const segs = Object.keys(o.stats.segments).filter((s) => s !== "unknown").length;
  const parts = [plural(o.stats.customers, "customer")];
  if (segs) parts.push(plural(segs, "segment"));
  if (o.stats.votes) parts.push(`${o.stats.votes} upvotes`);
  if (o.stats.lastSeen) parts.push(`last seen ${humanAge(o.stats.lastSeen, now)}`);
  return parts.join(" · ");
}

function sourceLabel(store: Store, q: Quote): string {
  const s = store.source(q.sourceId);
  const bits = [s?.kind ?? "source"];
  if (q.segment) bits.push(q.segment);
  if (q.date) bits.push(q.date.slice(0, 10));
  return bits.join(" · ");
}

export function renderSpec(store: Store, config: ReceiptsConfig, options: WriteSpecOptions = {}): string {
  const now = asOf(config);
  const opps = store.opportunities.slice(0, options.top ?? 12);
  const kinds = [...new Set(store.sources.map((s) => s.kind))];
  const customers = store.customers();
  const lines: string[] = [];
  const draft = opps.some((o) => !o.requirement?.metric);

  lines.push(`# ${config.project}: evidence-backed spec`, "");
  lines.push(
    `<!-- Generated by receipts v${VERSION} on ${now.toISOString().slice(0, 10)} from ${options.storePath ?? config.store}. Edit freely: \`receipts check\` keeps you honest. -->`,
    "",
  );
  lines.push(
    `> **Evidence base:** ${plural(store.quotes.length, "verified quote")} from ${plural(customers, "customer")} across ${plural(store.sources.length, "source")} (${kinds.join(", ")}).`,
    `> Every requirement cites the customer quotes it rests on. Run \`receipts why R1\` to read them, and \`receipts check\` to verify them.`,
    "",
  );
  if (draft) {
    lines.push(
      "> [!NOTE]",
      "> Requirement titles below are drafts taken from what customers said. Rewrite each as the outcome you will build, and replace every `metric: TODO`. Run with `ANTHROPIC_API_KEY` set to get drafted titles and metrics.",
      "",
    );
  }

  opps.forEach((o, i) => {
    const rid = `R${i + 1}`;
    const req = o.requirement ?? { title: o.title };
    lines.push(`## ${rid}. ${req.title}`, "");
    lines.push(`because: [${citations(store, o, options.maxCitations ?? 12).join(", ")}]  # ${evidenceComment(o, now)}`);
    lines.push(`metric: ${req.metric ?? "TODO: how will you know this worked?"}`);
    lines.push(`opportunity: ${o.id} · ${o.theme} · score ${o.score}`, "");
    if (o.job) lines.push(`*${o.job}*`, "");
    if (req.rationale) lines.push(req.rationale, "");
    const shown = citations(store, o, options.quotesPerRequirement ?? 3);
    for (const id of shown) {
      const q = store.quote(id);
      if (!q) continue;
      lines.push(`> "${q.text.replace(/\s+/g, " ").trim()}" — ${q.id} · ${sourceLabel(store, q)}`, "");
    }
    if (o.quoteIds.length > shown.length) {
      lines.push(`<sub>+${o.quoteIds.length - shown.length} more: \`receipts why ${rid}\`</sub>`, "");
    }
  });

  const covered = new Set(opps.flatMap((o) => o.quoteIds));
  const tail = store.quotes.filter((q) => !covered.has(q.id)).length;
  lines.push("## Out of scope", "");
  lines.push(
    `${plural(store.opportunities.length - opps.length, "lower-scoring opportunity", "lower-scoring opportunities")} and ${plural(tail, "quote")} in the long tail are not in this spec. See them with \`receipts opportunities\` or \`receipts view\`.`,
    "",
  );
  lines.push(
    "<!-- To add a requirement without evidence, own it explicitly:\n## R99. Title\nbet: why you're betting, and how you'll find out\n-->",
    "",
  );
  return lines.join("\n");
}
